-- 위 SELECT는 사람이 보라고 찍는 것일 뿐 실행을 막지 않는다 — `-f`로 파일을 통째로
-- 돌리면 사람이 중간에 개입할 수 없어 MISMATCH가 있어도 COMMIT이 그대로 나간다.
-- 그래서 같은 조건을 DO 블록으로 다시 검사해 어긋나면 예외를 던진다. 예외가 나면
-- 트랜잭션 전체가 롤백되어 잘못된 값이 테이블에 남지 않는다.
DO $$
DECLARE
    bad_count int;
BEGIN
    SELECT count(*) INTO bad_count
    FROM (
        SELECT b.year_month_value
        FROM maintenance_bills b
        JOIN maintenance_bill_items i ON i.bill_id = b.id
        WHERE b.year_month_value BETWEEN '2025-08' AND '2025-11'
        GROUP BY b.year_month_value, b.charged_amount
        HAVING SUM(i.amount) <> b.charged_amount
    ) mismatched;

    IF bad_count > 0 THEN
        RAISE EXCEPTION '항목 합계가 당월부과액과 다른 달이 % 개다. 넣지 않는다.', bad_count;
    END IF;
END $$;

COMMIT;
